# finding square and cube of a number 
num = float(input("Enter a number: "))

# finding square of a number
square_root = num*num
square_root_1 = pow(num,2)
square_root_2 = num**2
print(f"Square root of {num} is: {square_root}")
print(f"Square root of {num} is: {square_root_1}")
print(f"Square root of {num} is: {square_root_2}")

# finding cube of a number 
cube_root = num*num*num
cube_root_1 = pow(num,3)
cube_root_2 = num**3
print(f"Cube root of {num} is: {cube_root}")
print(f"Cube root of {num} is: {cube_root_1}")
print(f"Cube root of {num} is: {cube_root_2}")